/* Keep destinations and share metadata in step with main.js language changes. */
(function () {
  var root = document.documentElement;
  var title = document.title;
  var desc = document.querySelector('meta[name="description"]').content;
  var schema = document.querySelector('script[type="application/ld+json"]');
  function syncLanguageDetails() {
    var zh = root.dataset.lang === 'zh';
    var localizedTitle = zh ? window.MS_I18N_ZH['meta.title'] : title;
    var localizedDesc = zh ? window.MS_I18N_ZH['meta.desc'] : desc;
    document.querySelectorAll('[data-href-en]').forEach(function (link) {
      link.href = link.getAttribute(zh ? 'data-href-zh' : 'data-href-en');
    });
    document.querySelectorAll('meta[property="og:title"], meta[name="twitter:title"], meta[property="og:image:alt"]').forEach(function (meta) { meta.content = localizedTitle; });
    document.querySelectorAll('meta[property="og:description"], meta[name="twitter:description"]').forEach(function (meta) { meta.content = localizedDesc; });
    document.querySelectorAll('meta[property="og:image"], meta[name="twitter:image"]').forEach(function (meta) {
      meta.content = 'https://moneyswitch.dev/assets/img/cloud-wallet-2026-10/cover-' + (zh ? 'zh' : 'en') + '.png';
    });
    if (schema) {
      var data = JSON.parse(schema.textContent);
      data.description = localizedDesc;
      schema.textContent = JSON.stringify(data);
    }
  }
  syncLanguageDetails();
  new MutationObserver(syncLanguageDetails).observe(root, { attributes: true, attributeFilter: ['data-lang'] });
})();
