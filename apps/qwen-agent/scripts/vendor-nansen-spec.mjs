#!/usr/bin/env node
/**
 * Regenerates test/fixtures/nansen-openapi.subset.json: a small, checked-in,
 * fully-$ref-resolved slice of Nansen's real OpenAPI spec, containing only
 * the POST requestBody schemas for the 5 endpoints in src/catalog.ts.
 *
 * The full spec (~800KB, downloaded from https://api.nansen.ai/openapi.json)
 * is NOT checked in — it lives at .data/nansen-openapi.json (gitignored).
 * This script trims it down to just what test/unit/catalog-schema.test.ts
 * needs, so that test stays fast and doesn't require network access or a
 * local copy of the full spec to run in CI.
 *
 * Usage:
 *   node scripts/vendor-nansen-spec.mjs [path/to/nansen-openapi.json]
 *
 * Defaults to <repo root>/.data/nansen-openapi.json if no path is given.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const APP_DIR = path.resolve(SCRIPT_DIR, "..");
const REPO_ROOT = path.resolve(APP_DIR, "..", "..");

const SOURCE_URL = "https://api.nansen.ai/openapi.json";

const PATHS = [
  "/api/v1/token-screener",
  "/api/v1/tgm/flow-intelligence",
  "/api/v1/tgm/dex-trades",
  "/api/v1/smart-money/netflow",
  "/api/v1/smart-money/holdings",
];

function resolveRef(spec, ref) {
  const parts = ref.replace(/^#\//, "").split("/");
  let cur = spec;
  for (const part of parts) {
    cur = cur?.[part];
  }
  if (cur === undefined) {
    throw new Error(`Could not resolve $ref ${ref}`);
  }
  return cur;
}

/** Fully resolve $refs, inlining them. Breaks cycles (same $ref seen twice
 * on the current branch) by leaving the innermost occurrence as a bare
 * `{ "$ref": "..." }` marker instead of recursing forever — none of the 5
 * schemas here are actually cyclic, but this keeps the script safe if the
 * upstream spec grows a recursive schema later. */
function deref(spec, schema, seenOnBranch) {
  if (schema === null || typeof schema !== "object") return schema;

  if (Array.isArray(schema)) {
    return schema.map((item) => deref(spec, item, seenOnBranch));
  }

  if (typeof schema.$ref === "string") {
    if (seenOnBranch.has(schema.$ref)) {
      return { $ref: schema.$ref };
    }
    const nextSeen = new Set(seenOnBranch);
    nextSeen.add(schema.$ref);
    return deref(spec, resolveRef(spec, schema.$ref), nextSeen);
  }

  const out = {};
  for (const [key, value] of Object.entries(schema)) {
    out[key] = deref(spec, value, seenOnBranch);
  }
  return out;
}

function main() {
  const inputArg = process.argv[2];
  const specPath = inputArg
    ? path.resolve(process.cwd(), inputArg)
    : path.join(REPO_ROOT, ".data", "nansen-openapi.json");

  if (!fs.existsSync(specPath)) {
    console.error(`Nansen OpenAPI spec not found at ${specPath}`);
    console.error("Download it from https://api.nansen.ai/openapi.json or pass a path argument.");
    process.exit(1);
  }

  const spec = JSON.parse(fs.readFileSync(specPath, "utf-8"));

  const outPaths = {};
  for (const p of PATHS) {
    const item = spec.paths?.[p];
    if (!item?.post?.requestBody) {
      throw new Error(`Spec is missing POST requestBody for ${p} — cannot vendor subset.`);
    }
    const schema = item.post.requestBody.content?.["application/json"]?.schema;
    if (!schema) {
      throw new Error(`Spec is missing application/json requestBody schema for ${p}.`);
    }
    outPaths[p] = {
      post: {
        requestBody: {
          content: {
            "application/json": {
              schema: deref(spec, schema, new Set()),
            },
          },
        },
      },
    };
  }

  const fixture = {
    _comment:
      "VENDORED, TRIMMED, $ref-RESOLVED subset of Nansen's OpenAPI spec. " +
      "Generated by apps/qwen-agent/scripts/vendor-nansen-spec.mjs — do not hand-edit.",
    _source_url: SOURCE_URL,
    _vendored_at: "2026-09-27",
    paths: outPaths,
  };

  const outDir = path.join(APP_DIR, "test", "fixtures");
  fs.mkdirSync(outDir, { recursive: true });
  const outPath = path.join(outDir, "nansen-openapi.subset.json");
  fs.writeFileSync(outPath, JSON.stringify(fixture, null, 2) + "\n", "utf-8");
  console.log(`Wrote ${outPath}`);
}

main();
