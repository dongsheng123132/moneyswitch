// Regenerates site/assets/js/payments.js from site-data/testnet-payments.json.
// Usage: node site-data/build-site-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(readFileSync(join(here, 'testnet-payments.json'), 'utf8'));
for (const p of src.payments) {
  if (!/^0x[0-9a-f]{64}$/.test(p.tx)) throw new Error('bad tx ' + p.tx);
  if (p.explorer !== 'https://testnet.monadvision.com/tx/' + p.tx) throw new Error('explorer mismatch ' + p.tx);
}
const LABELS = ['claude-code', 'admin-approved', 'first-payment', 'wallet-test-out', 'wallet-test-back'];
for (const p of src.payments) if (p.label && !LABELS.includes(p.label)) throw new Error('unknown label ' + p.label);
if (src.count !== src.payments.length) throw new Error('count mismatch');
const out = '/* generated by site-data/build-site-data.mjs from site-data/testnet-payments.json — do not edit */\n' +
  'window.MS_PAYMENTS = ' + JSON.stringify(src, null, 1) + ';\n';
writeFileSync(join(here, '..', 'site', 'assets', 'js', 'payments.js'), out);
console.log('wrote payments.js', src.payments.length, 'payments');
